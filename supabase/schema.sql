-- ============================================================================
-- Vietnam Trip — initial Supabase schema, security and storage setup
-- ============================================================================
--
-- WHAT THIS IS
-- This is documentation/setup SQL. Paste the whole file into the Supabase
-- SQL Editor and run it manually. Nothing in this repository executes it —
-- the running app does NOT connect to Supabase yet (that is a later step).
--
-- WHAT THIS DOES NOT DO
-- It does not move or copy any existing trip data. It only creates empty
-- tables, security policies, an image storage bucket, and Realtime wiring.
-- Migrating the current itinerary-backup.json content into these tables is
-- a separate, later step.
--
-- SOURCE OF TRUTH
-- Column names/shapes are taken directly from the app's current in-memory
-- model (post "Phase 0" refactor), specifically:
--   src/components/Itinerary.js   (stops: loc, date, desc, cost, photo,
--                                   journey, activities, accommodations,
--                                   accommodationWishlistUrl,
--                                   selectedAccommodationId)
--   src/components/Journey.js     (journey legs/stopovers — makeLeg/makeStopover)
--   src/components/ActivityGrid.js/ActivityCard.js/ActivityFields.js (activities)
--   src/components/AccommodationSection.js/AccommodationCard.js (accommodations)
--   src/lib/travellers.js         (traveller shape)
--   src/components/TripPlanner.js (depart/return/extraCosts)
--   src/components/CostSummary.js (extraCosts shape)
--
-- WHAT IS DELIBERATELY *NOT* CREATED HERE (derived UI state — stays client-side)
--   - MAP pins/routes/selection (derived from stops + the static
--     src/lib/mapCoordinates.js lookup table)
--   - VOTES dashboard groupings ("Everyone's picks" / "Contenders" / etc.)
--   - Cost Summary totals
--   - active navigation tab, MAP's selected destination
-- All of these are recomputed live from the tables below, exactly as the
-- app already does from its in-memory `stops` state.
--
-- SECURITY MODEL (revised after review)
-- The app will sign every site visitor in via Supabase anonymous auth
-- automatically. That alone gives them Postgres role `authenticated` — the
-- same role a real family member's session has — so a policy of "allow any
-- authenticated request" would really mean "allow anyone who finds the
-- public GitHub Pages URL". That is NOT an acceptable boundary for a
-- private trip, so it is not what this file does.
--
-- Instead, every table's access is gated on genuine trip MEMBERSHIP
-- (public.trip_access), which a visitor only gets by successfully calling
-- public.join_trip() with the trip's one shared invite code/passphrase —
-- see section 3 for the full mechanism and rationale. `authenticated` is
-- necessary but no longer sufficient anywhere in this file.
--
-- STABLE IDS
-- Every table uses a uuid primary key generated by the database
-- (gen_random_uuid()). Once a row is created, that id never changes — which
-- is exactly what "stable id" means for this app's reorder, MAP deep-link,
-- duplicate-Hanoi-stop, vote and accommodation-selection logic. (The current
-- app's short string ids like "idp0mix79k4zn8" are a JSON-seed artifact —
-- the later migration step will map each of those to a newly generated uuid
-- once, and from then on that uuid is permanent.)
--
-- RE-RUNNING THIS FILE
-- Written to be safe to run more than once: tables/indexes use
-- IF NOT EXISTS, and policies/triggers/publication entries are dropped and
-- re-created rather than erroring if they already exist. Re-running it will
-- NOT drop or change any data you've already put in these tables. It is
-- meant for the initial setup only — once the app is live, future schema
-- changes should be their own small additive SQL files, not edits to this
-- one (see the audit's "schema evolution" guidance).
--
-- ============================================================================


-- ----------------------------------------------------------------------------
-- 0. Extensions
-- ----------------------------------------------------------------------------
-- gen_random_uuid() — used as the default for every primary key below.
create extension if not exists pgcrypto;


-- ----------------------------------------------------------------------------
-- 1. Tables
-- ----------------------------------------------------------------------------
-- Created in dependency order. `stops` and `accommodations` reference each
-- other (a stop's selected stay is one of its own accommodation rows), so
-- `stops.selected_accommodation_id` is added as a plain column here and its
-- foreign key is attached afterwards with ALTER TABLE, once `accommodations`
-- exists — this avoids any circular create-order problem.

-- --- trips -------------------------------------------------------------
-- One row per trip. Only one row is expected to exist for now (this app has
-- no trip-switcher UI), but modelling it as its own table keeps every other
-- table cleanly scoped via trip_id, and leaves room for more trips later.
create table if not exists public.trips (
  id               uuid primary key default gen_random_uuid(),
  title            text,
  subtitle         text,
  depart           date,
  return_date      date,
  currency         text not null default '£',
  hero_photo_url   text,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);
comment on table public.trips is 'One row per trip. title/subtitle/hero photo are not yet editable in the app, but are modelled here so the full trip is represented.';

-- --- trip_invite_codes -----------------------------------------------------
-- The one shared "family passphrase" for this trip. Stored hashed
-- (pgcrypto's crypt()/gen_salt('bf')) so the plaintext code never sits in
-- the database at rest — only public.join_trip() below can check it, and
-- ordinary API access (anon or authenticated) is refused entirely (see the
-- RLS section: this table gets RLS enabled with NO policies for those
-- roles, so it isn't readable via the API at all, only via the function).
create table if not exists public.trip_invite_codes (
  trip_id     uuid primary key references public.trips(id) on delete cascade,
  code_hash   text not null,
  created_at  timestamptz not null default now()
);
comment on table public.trip_invite_codes is 'One shared invite code per trip, hashed. Never exposed directly via the API — only checked inside public.join_trip().';

-- --- trip_access -------------------------------------------------------
-- Real trip membership. This is the actual authorization boundary — every
-- other table's RLS policy checks THIS table (via is_trip_member below),
-- not merely "is this request authenticated". A row only ever appears here
-- via public.join_trip() succeeding; there is no direct-insert policy for
-- ordinary users.
create table if not exists public.trip_access (
  trip_id     uuid not null references public.trips(id) on delete cascade,
  user_id     uuid not null references auth.users(id) on delete cascade,
  joined_at   timestamptz not null default now(),
  primary key (trip_id, user_id)
);
comment on table public.trip_access is 'Trip membership: one row per (trip, Supabase auth user) that has successfully called join_trip() with the correct invite code. This table — not "authenticated" alone — is the real access boundary.';

