-- ----------------------------------------------------------------------------
-- 5. Row Level Security
-- ----------------------------------------------------------------------------
-- Model: this is one shared, private trip for a small trusted group. The
-- real boundary is trip MEMBERSHIP (trip_access, section 3) — not merely
-- "authenticated". Every application table's policy checks
-- is_trip_member(trip_id) (or, for tables one join away from a trip_id,
-- the equivalent EXISTS check up to their owning stop). An anonymous-auth
-- session that has never called join_trip() successfully has no row in
-- trip_access, so is_trip_member() returns false and every one of these
-- policies denies it — being "authenticated" is necessary but no longer
-- sufficient.
--
-- If finer-grained access (e.g. "only this traveller can edit their own
-- vote") is ever wanted, that's a later, additive policy change — not
-- needed for this trip.

-- trip_invite_codes: RLS enabled, NO policies for authenticated/anon at
-- all. That is deliberate, not an oversight — it means this table cannot be
-- read, inserted, updated or deleted via the API by anyone, ever; only
-- join_trip() (SECURITY DEFINER) can see it.
alter table public.trip_invite_codes enable row level security;

-- trip_access: a member may see their OWN membership rows (so the app can
-- ask "have I already joined this trip?"). No insert/update/delete policy
-- for ordinary roles — membership is only ever granted by join_trip().
alter table public.trip_access enable row level security;
drop policy if exists "read own membership" on public.trip_access;
create policy "read own membership" on public.trip_access
  for select to authenticated
  using (user_id = auth.uid());

alter table public.trips enable row level security;
drop policy if exists "authenticated full access" on public.trips;
drop policy if exists "trip members full access" on public.trips;
create policy "trip members full access" on public.trips
  for all to authenticated
  using (public.is_trip_member(id))
  with check (public.is_trip_member(id));

alter table public.travellers enable row level security;
drop policy if exists "authenticated full access" on public.travellers;
drop policy if exists "trip members full access" on public.travellers;
create policy "trip members full access" on public.travellers
  for all to authenticated
  using (public.is_trip_member(trip_id))
  with check (public.is_trip_member(trip_id));

alter table public.stops enable row level security;
drop policy if exists "authenticated full access" on public.stops;
drop policy if exists "trip members full access" on public.stops;
create policy "trip members full access" on public.stops
  for all to authenticated
  using (public.is_trip_member(trip_id))
  with check (public.is_trip_member(trip_id));

-- accommodations/journey_items/activities are one join away from trip_id
-- (via their owning stop) rather than having their own trip_id column —
-- kept that way deliberately, to avoid denormalizing trip_id onto every
-- table just to simplify these policies. The EXISTS below is the small,
-- direct cost of that choice.
alter table public.accommodations enable row level security;
drop policy if exists "authenticated full access" on public.accommodations;
drop policy if exists "trip members full access" on public.accommodations;
