-- ----------------------------------------------------------------------------
-- 4. updated_at trigger
-- ----------------------------------------------------------------------------
-- One shared trigger function, applied to every table that has an
-- updated_at column, so "when was this last touched" is always accurate
-- and set by the database itself — never something the app has to remember
-- to set on every write.

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists set_updated_at on public.trips;
create trigger set_updated_at
  before update on public.trips
  for each row execute function public.set_updated_at();

drop trigger if exists set_updated_at on public.travellers;
create trigger set_updated_at
  before update on public.travellers
  for each row execute function public.set_updated_at();

drop trigger if exists set_updated_at on public.stops;
