drop policy if exists "trip members full access" on public.extra_costs;
create policy "trip members full access" on public.extra_costs
  for all to authenticated
  using (public.is_trip_member(trip_id))
  with check (public.is_trip_member(trip_id));


-- ----------------------------------------------------------------------------
-- 6. Storage — trip photos bucket
-- ----------------------------------------------------------------------------
-- Destination photos, activity images, accommodation images and the hero
-- photo all go in one bucket as files; the tables above only ever store the
-- resulting URL/path (photo_url / image_url / hero_photo_url), never image
-- bytes/base64.
--
-- PRIVATE bucket (public = false), gated by the same trip membership as
-- every table above — not merely "authenticated". Earlier drafts of this
-- file made the bucket publicly readable for simplicity; on review, that
-- doesn't fit "private family trip" once anonymous auth means literally
-- any site visitor can become "authenticated", so it's replaced with the
-- same is_trip_member() check used everywhere else.
--
-- HOW THIS WORKS: every uploaded file's path must start with its trip's id
-- as the first folder segment, e.g. `<trip_id>/stops/<stop_id>/photo.jpg`.
-- storage.foldername(name) splits that path into segments; the policies
-- below check that segment [1] is a trip the caller is a member of. This is
-- a real, load-bearing consequence for whoever wires up uploads later: the
-- upload code must put files under that `<trip_id>/...` prefix, and because
-- the bucket is private, the frontend must fetch images via an authenticated
-- request (e.g. supabase.storage.from('trip-photos').download(...) or a
-- signed URL) rather than a plain public CDN <img src> URL.

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'trip-photos',
  'trip-photos',
  false,
  10485760, -- 10 MB per file
  array['image/jpeg', 'image/png', 'image/webp', 'image/gif']
)
on conflict (id) do update
  set public = excluded.public,
      file_size_limit = excluded.file_size_limit,
      allowed_mime_types = excluded.allowed_mime_types;

-- NOTE ON OWNERSHIP: storage.objects is a Supabase-MANAGED table, owned by
-- an internal Supabase role (not by the `postgres`/project-owner role this
-- script runs as). Row Level Security is already permanently enabled on it
-- by Supabase — you cannot toggle it yourself, and trying to
-- (`alter table storage.objects enable row level security;`) fails with
-- `ERROR: 42501: must be owner of table objects`, because ALTER TABLE
-- requires true table ownership regardless of what state RLS is already
-- in. That line used to be here and has been removed — it was never
-- needed, only harmful. CREATE POLICY / DROP POLICY on storage.objects are
-- unaffected by this and are the actual, Supabase-supported way to manage
-- its access rules; only structural ALTER TABLE on storage.objects itself
-- is off-limits to a project owner.

drop policy if exists "Public read access for trip photos" on storage.objects;
drop policy if exists "Trip members can read trip photos" on storage.objects;
create policy "Trip members can read trip photos"
  on storage.objects for select
  to authenticated
  using (
    bucket_id = 'trip-photos'
    and public.is_trip_member((storage.foldername(name))[1]::uuid)
  );

drop policy if exists "Authenticated upload trip photos" on storage.objects;
drop policy if exists "Trip members can upload trip photos" on storage.objects;
create policy "Trip members can upload trip photos"
  on storage.objects for insert
  to authenticated
  with check (
    bucket_id = 'trip-photos'
    and public.is_trip_member((storage.foldername(name))[1]::uuid)
  );

drop policy if exists "Authenticated update trip photos" on storage.objects;
drop policy if exists "Trip members can update trip photos" on storage.objects;
create policy "Trip members can update trip photos"
  on storage.objects for update
  to authenticated
  using (
    bucket_id = 'trip-photos'
    and public.is_trip_member((storage.foldername(name))[1]::uuid)
  )
  with check (
    bucket_id = 'trip-photos'
    and public.is_trip_member((storage.foldername(name))[1]::uuid)
  );

drop policy if exists "Authenticated delete trip photos" on storage.objects;
drop policy if exists "Trip members can delete trip photos" on storage.objects;
create policy "Trip members can delete trip photos"
  on storage.objects for delete
  to authenticated
  using (
    bucket_id = 'trip-photos'
    and public.is_trip_member((storage.foldername(name))[1]::uuid)
  );


-- ----------------------------------------------------------------------------
-- 7. Realtime
-- ----------------------------------------------------------------------------
-- trip_access / trip_invite_codes are deliberately NOT added here: they
-- change rarely, the app has no need to watch them live, and
-- trip_invite_codes should never be surfaced to a Realtime subscription at
-- all (Realtime respects RLS, but there is simply no reason to include it).
-- Adds every application table to Supabase's built-in `supabase_realtime`
-- publication, so any of them CAN be subscribed to later for live updates
-- (e.g. "Dom votes -> Sarah sees it without refreshing"). Being in the
-- publication costs nothing on its own — nothing broadcasts until the app
-- actually opens a Realtime subscription, which it does not do yet.
--
-- This assumes the `supabase_realtime` publication already exists, which it
-- does on every standard Supabase project by default.
--
-- REPLICA IDENTITY FULL is set on each table so that a future UPDATE/DELETE
-- Realtime event carries the complete old row, not just its primary key —
-- lets the app merge a change without an extra fetch. This only affects
-- what's logged for replication; it has no effect on the app today.

do $$
declare
  t text;
begin
  foreach t in array array[
    'trips', 'travellers', 'stops', 'journey_items',
    'activities', 'activity_votes',
    'accommodations', 'accommodation_votes', 'extra_costs'
  ]
  loop
    execute format('alter table public.%I replica identity full', t);

    if not exists (
      select 1 from pg_publication_tables
      where pubname = 'supabase_realtime'
        and schemaname = 'public'
        and tablename = t
    ) then
      execute format('alter publication supabase_realtime add table public.%I', t);
    end if;
  end loop;
end $$;


