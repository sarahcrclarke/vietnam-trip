-- ----------------------------------------------------------------------------
-- 3. Trip membership — invite code + access check
-- ----------------------------------------------------------------------------
-- WHY THIS EXISTS: the app will sign every visitor in via Supabase anonymous
-- auth automatically. Once signed in, that visitor's session has Postgres
-- role `authenticated` — the SAME role a genuine family member's session
-- has. A policy that simply says "anyone authenticated may read/write" is
-- therefore equivalent to "anyone who finds the public GitHub Pages URL and
-- loads the page" — since the app itself silently grants every visitor an
-- authenticated session with no gate in between. `authenticated` alone is
-- NOT a meaningful boundary for a public static site; it only proves "this
-- is a real browser session", not "this person is family".
--
-- THE FIX: a single shared trip invite code (a passphrase, not a password —
-- no email/account). A visitor enters it once; the app calls join_trip()
-- below, which checks the code and — only on success — inserts a row into
-- trip_access for their session's user id. From then on their session is a
-- genuine trip member, and every table's RLS policy (section 4) checks
-- trip_access, not just "authenticated". The code is entered once per
-- browser (Supabase's own SDK already persists the session in localStorage,
-- same as any Supabase app) — no repeated friction for family members who
-- don't clear their browser data.

-- Small stable helper so every table's RLS policy can say
-- `is_trip_member(trip_id)` instead of repeating this subquery everywhere.
-- SECURITY DEFINER + a locked-down search_path is the standard, documented
-- Supabase pattern for auth-check helpers called from inside RLS policies.
create or replace function public.is_trip_member(p_trip_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.trip_access
    where trip_id = p_trip_id and user_id = auth.uid()
  );
$$;

revoke execute on function public.is_trip_member(uuid) from public;
grant execute on function public.is_trip_member(uuid) to authenticated;

-- The only way a row can ever appear in trip_access. Runs with the
-- function owner's privileges (SECURITY DEFINER), which is how it's allowed
-- to read the otherwise-inaccessible trip_invite_codes table and insert
-- into trip_access even though ordinary sessions have no direct grant to do
-- either — the invite-code check happens here, once, server-side, not in
-- the browser.
create or replace function public.join_trip(trip_code text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_trip_id uuid;
begin
  if auth.uid() is null then
    raise exception 'Not authenticated';
  end if;

  select trip_id into v_trip_id
  from public.trip_invite_codes
  where code_hash = crypt(trip_code, code_hash)
  limit 1;

  if v_trip_id is null then
    raise exception 'Invalid trip code';
  end if;

  insert into public.trip_access (trip_id, user_id)
  values (v_trip_id, auth.uid())
  on conflict (trip_id, user_id) do nothing;
end;
$$;

revoke execute on function public.join_trip(text) from public;
grant execute on function public.join_trip(text) to authenticated;

