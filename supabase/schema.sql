  traveller_id  uuid not null references public.travellers(id) on delete cascade,
  created_at    timestamptz not null default now(),
  primary key (activity_id, traveller_id)
);
comment on table public.activity_votes is 'One row = one traveller''s vote for one activity. Vote = row exists. Un-vote = row deleted.';

