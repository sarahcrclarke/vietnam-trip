-- --- activity_votes --------------------------------------------------------
-- A normalized row per traveller/activity — presence of a row IS the vote
-- (binary selected/not-selected, matching the app's voting model exactly).
-- This is deliberately NOT a shared jsonb column on `activities`: two people
